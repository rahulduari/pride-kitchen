const categoryList = document.getElementById("category-list");
const selectedCategory = document.getElementById("selected-category");
const foodContent = document.getElementById("food-content");
const foodDisplay = document.getElementById("food-display");


// =====================================
// CATEGORY BUTTONS
// =====================================

function loadCategories() {

    categoryList.innerHTML = "";

    Object.keys(menuData).forEach((category, index) => {

        const button = document.createElement("button");

        button.className = "category";
        button.textContent = category;

        button.addEventListener("click", () => {

            document.querySelectorAll(".category").forEach(btn => {
                btn.classList.remove("active");
            });

            button.classList.add("active");

            loadFoodItems(category);

        });

        categoryList.appendChild(button);

        if (index === 0) {
            button.classList.add("active");
            loadFoodItems(category);
        }

    });

}


// =====================================
// FOOD ITEMS
// =====================================

function loadFoodItems(category) {

    selectedCategory.textContent = category;

    foodContent.innerHTML = "";

    const groups = menuData[category];

    Object.keys(groups).forEach(groupName => {

        const group = document.createElement("div");
        group.className = "food-group";

        const heading = document.createElement("h4");
        heading.textContent = groupName;

        group.appendChild(heading);

        groups[groupName].forEach(food => {

            const item = document.createElement("div");

            item.className = "food-item";

            const foodName = document.createElement("span");
            foodName.className = "food-name";

            const icon = document.createElement("span");

            if (groupName === "VEG") {
                icon.className = "veg-icon";
            } else if (
                groupName === "NON-VEG" ||
                groupName === "MUTTON" ||
                groupName === "CHICKEN / EGG"
            ) {
                icon.className = "nonveg-icon";
            }

            foodName.appendChild(icon);
            foodName.appendChild(document.createTextNode(food));

            item.appendChild(foodName);

            // Display price beside dish name

            const price = priceData[food];

            const priceLabel = document.createElement("span");
            priceLabel.className = "food-price";

            if (typeof price === "number") {

                priceLabel.textContent = `₹${price}`;

            } else if (price && typeof price === "object") {

                const startingPrice = Math.min(...Object.values(price));

                priceLabel.textContent = `From ₹${startingPrice}`;

            } else {

                priceLabel.textContent = "Price unavailable";

            }

            item.appendChild(priceLabel);

            item.addEventListener("click", () => {

                showFoodDetails(food, groupName);

            });

            group.appendChild(item);

        });

        foodContent.appendChild(group);

    });


    // Reset right panel when changing category

    foodDisplay.innerHTML = `
        <div class="food-placeholder">
            <span>🍽️</span>
            <h3>${category}</h3>
            <p>Select a dish to explore its details.</p>
        </div>
    `;

}


// =====================================
// SELECTED FOOD DETAILS
// =====================================

function showFoodDetails(food, groupName) {

    // Generate image filename using existing naming convention

    const slug = food
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");


    const price = priceData[food];

    let priceSection = "";


    // Single-price dishes

    if (typeof price === "number") {

        priceSection = `
            <p class="selected-food-price">
                Price: ₹${price}
            </p>
        `;

    }

    // Dishes with selectable sizes or portions

    else if (price && typeof price === "object") {

        const options = Object.entries(price)
            .map(([variant, amount]) =>
                `<option value="${amount}">${variant} - ₹${amount}</option>`
            )
            .join("");

        const firstPrice = Object.values(price)[0];

        priceSection = `
            <div class="food-variant-section">

                <label for="food-variant">
                    Choose portion / size:
                </label>

                <select id="food-variant">
                    ${options}
                </select>

                <p class="selected-food-price" id="selected-food-price">
                    Price: ₹${firstPrice}
                </p>

            </div>
        `;

    }

    // Missing price protection

    else {

        priceSection = `
            <p class="selected-food-price">
                Price unavailable
            </p>
        `;

    }


    foodDisplay.innerHTML = `
        <div class="selected-food-details">

            <div class="image-placeholder" id="image-placeholder">
                🍽️
            </div>

            <img
                src="/images/menu/${slug}.jpeg"
                alt="${food}"
                class="selected-food-image"
                id="selected-food-image"
                style="display:none;"
            >

            <h3>${food}</h3>

            ${priceSection}

            <p>
                Freshly prepared with delicious ingredients
                at Pride Kitchen.
            </p>

            <p class="food-type">
                ${groupName}
            </p>

        </div>
    `;


    // Update price when customer changes size / portion

    const variantSelect = document.getElementById("food-variant");

    if (variantSelect) {

        variantSelect.addEventListener("change", () => {

            const selectedPrice = document.getElementById("selected-food-price");

            selectedPrice.textContent =
                `Price: ₹${variantSelect.value}`;

        });

    }


    // Handle food image

    const image = document.getElementById("selected-food-image");

    const placeholder = document.getElementById("image-placeholder");


    image.onload = () => {

        image.style.display = "block";

        placeholder.style.display = "none";

    };


    image.onerror = () => {

        image.style.display = "none";

        placeholder.style.display = "flex";

    };

}


